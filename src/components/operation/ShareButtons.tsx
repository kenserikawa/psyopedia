export function ShareButtons({ url, title }: ShareButtonsProps) {
  const t = useTranslations("operation");
  const [copied, setCopied] = useState(false);
  // Hydration-safe capability check: false on the server, real value on the client
  const canNativeShare = useSyncExternalStore(
    emptySubscribe,
    () => !!navigator.share,
    () => false
  );

  const copyLink = async () => {
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard unavailable (insecure context) — nothing to do
    }
  };

  const openShare = (shareUrl: string) => {
    window.open(shareUrl, "_blank", "noopener,noreferrer,width=600,height=550");
  };

  const encodedUrl = encodeURIComponent(url);
  const encodedTitle = encodeURIComponent(title);

  return (
    <div className="flex flex-wrap items-center gap-2">
      <span className="text-sm font-medium text-muted-foreground">{t("share")}:</span>
      {canNativeShare && (
        <Button
          variant="outline"
          size="icon-sm"
          aria-label={t("share")}
          onClick={() => navigator.share({ title, url }).catch(() => {})}
        >
          <Share2 />
        </Button>
      )}
      <Button
        variant="outline"
        size="icon-sm"
        aria-label="X"
        onClick={() => openShare(`https://x.com/intent/post?url=${encodedUrl}&text=${encodedTitle}`)}
      >
        <XIcon />
      </Button>
      <Button
        variant="outline"
        size="icon-sm"
        aria-label="Facebook"
        onClick={() => openShare(`https://www.facebook.com/sharer/sharer.php?u=${encodedUrl}`)}
      >
        <FacebookIcon />
      </Button>
      <Button
        variant="outline"
        size="icon-sm"
        aria-label="Reddit"
        onClick={() => openShare(`https://www.reddit.com/submit?url=${encodedUrl}&title=${encodedTitle}`)}
      >
        <RedditIcon />
      </Button>
      <Button
        variant="outline"
        size="icon-sm"
        aria-label="WhatsApp"
        onClick={() => openShare(`https://wa.me/?text=${encodedTitle}%20${encodedUrl}`)}
      >
        <WhatsAppIcon />
      </Button>
      <Button variant="outline" size="sm" onClick={copyLink}>
        {copied ? <Check /> : <Link2 />}
        {copied ? t("linkCopied") : t("copyLink")}
      </Button>
    </div>
  );
}
